import streamlit as st


def render_about():
    st.markdown("## About This Project")
    st.markdown(
        "**Project Title:** Machine Learning-Based Binary Classification of Antibiotic Resistance Genes (ARGs) "
        "vs Non-ARGs Using Protein Sequences."
    )

    st.markdown("---")

    col_meta1, col_meta2 = st.columns([3, 2])

    with col_meta1:
        st.markdown("""
        ### Academic Research Objective
        To develop a robust, leakage-free machine learning system capable of classifying protein sequences 
        as Antibiotic Resistance Gene (ARG) products or candidate non-ARG housekeeping proteins. 

        By extracting 428 alignment-free compositional and biophysical descriptors (Amino Acid Composition, 
        Dipeptide Composition, and Physicochemical Properties), the framework provides rapid in silico screening 
        of metagenomic and genomic contigs without relying on high-identity BLAST alignments.

        ### Key Scientific Innovations
        1. **Homology-Leakage Elimination:** Two-stage MMseqs2 clustering at 30% sequence identity coupled with 
           Mixed-Integer Linear Programming (MILP) partition optimization ensures zero cluster splitting across train, val, and test.
        2. **Locked, Reproducible Preprocessing:** Single frozen `StandardScaler` fitted strictly on training data; 
           exact 428-feature pipeline identical between training and live inference.
        3. **Validation-Selected Decision Threshold:** Empirically tuned threshold ($t = 0.10$) preserves high sensitivity 
           on distant protein superfamilies under zero-homology testing.
        """)

    with col_meta2:
        st.markdown("""
        ### Data & Provenance Sources
        - **Positive ARGs:** Comprehensive Antibiotic Resistance Database (CARD) v4.0.2.
        - **Candidate Non-ARGs:** UniProtKB/Swiss-Prot release 2024_06 (reviewed bacterial housekeeping enzymes).
        - **Total Dataset:** 12,108 curated sequences (6,054 positive, 6,054 negative).

        ### Machine Learning Stack
        - **Python 3.11**
        - **Streamlit 1.66.0** (Interactive UI & Navigation)
        - **Scikit-learn 1.9.1** (Random Forest, Logistic Regression, RBF-SVM, StandardScaler)
        - **Biopython 1.88** (FASTA parsing, SeqUtils ProtParam)
        - **Plotly 7.1.0** (Interactive analytical charts)
        - **Pandas 3.0.6 & NumPy 2.4.6** (Data structures & matrix operations)
        """)

    st.markdown("---")

    # Local Processing Guarantee Card
    st.markdown("""
    ### 🔒 Local Privacy & Computational Security Guarantee
    - **100% Local Inference:** All sequence parsing, feature extraction, scaling, and model inference execute strictly within your local Python environment.
    - **Zero Cloud Transmission:** No amino acid sequences, query headers, file contents, or model outputs are ever uploaded to external servers, APIs, or third-party cloud infrastructure.
    - **Offline Operation:** The entire application operates completely offline without an active internet connection.
    """)

    st.markdown("---")

    # Research Governance & Ethics Disclaimer
    st.warning("""
    ### ⚠️ Academic Research Disclaimer
    This software is an in silico academic research demonstration created for data analytics and computational biology demonstration. 
    It is not an in vitro diagnostic device or a clinical decision-support tool. Predictions generated by this tool represent computational 
    hypotheses that must be independently validated through wet-lab experimental biology, including gene expression assays and standardized 
    antimicrobial susceptibility testing (e.g. EUCAST or CLSI minimum inhibitory concentration broth microdilution).
    """)
